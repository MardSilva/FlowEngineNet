    private static readonly ImmutableDictionary<string, string> English = CreateEnglish();
    private static readonly ImmutableDictionary<string, string> Portuguese = CreatePortuguese();
    private readonly ImmutableDictionary<string, string> _values;

    public FlowWindowsTextCatalog(string language)
    {
        Language = string.Equals(language, FlowWindowsSettings.PortugueseBrazil, StringComparison.OrdinalIgnoreCase)
            ? FlowWindowsSettings.PortugueseBrazil
            : FlowWindowsSettings.English;
        _values = Language == FlowWindowsSettings.PortugueseBrazil ? Portuguese : English;
    }

    public string Language { get; }

    public string this[string key] => _values.TryGetValue(key, out var value)
        ? value
        : throw new KeyNotFoundException($"Shell text '{key}' is not defined for {Language}.");

    public ImmutableArray<string> Keys => [.. _values.Keys];

